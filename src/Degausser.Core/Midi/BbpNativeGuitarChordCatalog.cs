    internal static bool TryResolve(ushort chordId, out uint packedVoicing)
    {
        int low = 0;
        int high = Records.Length / RecordSize - 1;

        while (low <= high)
        {
            int middle = low + ((high - low) >> 1);
            int offset = middle * RecordSize;
            ushort candidate = BinaryPrimitives.ReadUInt16LittleEndian(Records.AsSpan(offset, 2));

            if (candidate == chordId)
            {
                packedVoicing = BinaryPrimitives.ReadUInt32LittleEndian(Records.AsSpan(offset + 2, 4));
                return true;
            }

            if (candidate < chordId)
                low = middle + 1;
            else
                high = middle - 1;
        }

        packedVoicing = 0;
        return false;
    }
